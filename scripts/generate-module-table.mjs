// -----------------------------------------------------------------------------
// Builds src/velbus/module-table.js from the module descriptions of velbus-aio
// (velbusaio/module_spec/*.json, see THIRD_PARTY_NOTICES.md). Dev tool only,
// never shipped in the image:
//
//   node scripts/generate-module-table.mjs <velbus-aio>/velbusaio/module_spec
//
// Only what this integration uses is kept: the channels it shows (relays,
// dimmers, blinds, buttons, temperature), the message variant of each
// command it reads or sends, the temperature channel, the thermostat flag,
// the channel number map and the dimmer scale. DALI modules are left out
// (their channels are discovered on the DALI bus, not in the description).
// -----------------------------------------------------------------------------

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const KINDS = new Set(['Relay', 'Dimmer', 'Blind', 'Button', 'Temperature']);
const COMMANDS = [
  '00', // push button status
  '01', // relay off
  '02', // relay on
  '04', // blind stop
  '05', // blind up
  '06', // blind down
  '07', // set dimmer
  '0F', // slider status
  '11', // restore dimmer
  '1C', // blind position
  'A5', // dim values status
  'B0', // sub addresses
  'B8', // dimmer channel status
  'DB', // preset comfort
  'DC', // preset day
  'DD', // preset night
  'DE', // preset safe
  'E4', // set temperature
  'E6', // sensor temperature
  'EA', // thermostat status
  'EC', // blind status
  'EE', // dimmer status
  'EF', // channel name request
  'F0', // channel name part 1 (parts 2 and 3 use the same variant)
  'FB', // relay status
  'FF', // module type
];
const DALI = new Set([0x45, 0x5a]);

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/generate-module-table.mjs <module_spec directory>');
  process.exit(1);
}

const entries = [];
for (const file of readdirSync(dir).sort()) {
  if (!/^[0-9A-F]{2}\.json$/.test(file)) continue;
  const type = Number.parseInt(file.slice(0, 2), 16);
  const spec = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  const channels = Object.entries(spec.Channels ?? {})
    .filter(([, c]) => KINDS.has(c.Type))
    .map(([num, c]) => [
      Number.parseInt(num, 10),
      c.Type.toLowerCase(),
      c.Name,
      c.Editable === 'yes',
    ])
    .sort((a, b) => a[0] - b[0]);
  const classes = Object.fromEntries(
    COMMANDS.filter((c) => spec.CommandToClass?.[c]).map((c) => [c, spec.CommandToClass[c]]),
  );
  const nameMap = Object.entries(spec.ChannelNumbers?.Name?.Map ?? {}).map(([from, to]) => [
    Number.parseInt(from, 16),
    Number.parseInt(to, 10),
  ]);
  entries.push({
    type,
    name: spec.Type,
    supported: !DALI.has(type) && channels.length > 0,
    channels: DALI.has(type) ? [] : channels,
    classes: DALI.has(type) ? {} : classes,
    allChannelStatus: spec.AllChannelStatus === 'FF',
    temperatureChannel:
      spec.TemperatureChannel === undefined ? null : Number.parseInt(spec.TemperatureChannel, 10),
    // velbus-aio: a thermostat when the description has "Thermostat" or "ThermostatAddr".
    thermostat: 'Thermostat' in spec || 'ThermostatAddr' in spec,
    nameMap,
    sliderScale: spec.sliderScale ?? 100,
  });
}

const header = `// -----------------------------------------------------------------------------
// GENERATED by scripts/generate-module-table.mjs from velbus-aio 2026.9.0
// (velbusaio/module_spec/*.json, Apache-2.0 / MIT, see THIRD_PARTY_NOTICES.md).
// Do not edit by hand: run the script again.
//
// One entry per Velbus module type: [channel, kind, default name, name
// editable] for the channels shown, and the velbus-aio message variant of each
// command read or sent.
// -----------------------------------------------------------------------------

/* prettier-ignore */
export const MODULE_SPECS = ${JSON.stringify(entries)};
`;
const out = new URL('../src/velbus/module-table.js', import.meta.url);
writeFileSync(
  out,
  header
    .replace(/\},\{"type"/g, '},\n  {"type"')
    .replace('[{"type"', '[\n  {"type"')
    .replace(/\}\];\n$/, '},\n];\n'),
  'utf8',
);
console.log(
  `${entries.length} module types, ${entries.filter((e) => e.supported).length} supported`,
);
